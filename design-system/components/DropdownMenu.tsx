const DropdownMenuItem = React.forwardRef<
  React.ElementRef<typeof DropdownMenuPrimitive.Item>,
  React.ComponentPropsWithoutRef<typeof DropdownMenuPrimitive.Item> & {
    inset?: boolean;
    variant?: 'default' | 'danger';
  }
>(({ className, inset, variant = 'default', ...props }, ref) => (
  <DropdownMenuPrimitive.Item
    ref={ref}
    className={cn(
      "relative flex cursor-default select-none items-center rounded-[var(--radius-sm)] px-2.5 py-1.5 text-sm outline-none transition-colors focus:bg-[var(--color-accent)] data-[disabled]:pointer-events-none data-[disabled]:opacity-40 text-[var(--color-text-main)] font-medium",
      inset && "pl-8",
      variant === 'danger' && "text-[var(--color-overdue)] focus:bg-[var(--color-overdue)]/10 focus:text-[var(--color-overdue)]",
      className
    )}
    {...props}
  />
))
DropdownMenuItem.displayName = DropdownMenuPrimitive.Item.displayName

